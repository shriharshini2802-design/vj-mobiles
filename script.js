// ========================================
// 1. ACCESSORY CLICK
// ========================================

function selectAccessory(accessory) {

    localStorage.setItem(
        "selectedAccessory",
        accessory
    );

    window.location.href =
        "brands.html";
}



// ========================================
// 2. LOAD BRANDS
// ========================================

if (
    window.location.pathname.endsWith(
        "brands.html"
    )
) {

    const accessory =
        localStorage.getItem(
            "selectedAccessory"
        );


    const heading =
        document.getElementById(
            "accessoryHeading"
        );


    const brandList =
        document.getElementById(
            "brandList"
        );


    if (
        accessory &&
        accessories[accessory]
    ) {

        heading.textContent =
            accessory.toUpperCase();


        const brands =
            Object.keys(
                accessories[accessory]
            );


        brands.forEach(
            function (brand) {

                const card =
                    document.createElement(
                        "div"
                    );


                card.className =
                    "brand-card";


                card.innerHTML = `

                    <div class="brand-logo">
                        ${brand.charAt(0)}
                    </div>

                    <h2>
                        ${brand}
                    </h2>

                    <p>
                        View Models →
                    </p>

                `;


                card.onclick =
                    function () {

                        localStorage.setItem(
                            "selectedBrand",
                            brand
                        );


                        window.location.href =
                            "models.html";

                    };


                brandList.appendChild(
                    card
                );

            }
        );

    }

}



// ========================================
// 3. LOAD MODELS
// ========================================

if (
    window.location.pathname.endsWith(
        "models.html"
    )
) {

    const accessory =
        localStorage.getItem(
            "selectedAccessory"
        );


    const brand =
        localStorage.getItem(
            "selectedBrand"
        );


    const heading =
        document.getElementById(
            "brandHeading"
        );


    const modelList =
        document.getElementById(
            "modelList"
        );


    if (
        accessory &&
        brand &&
        accessories[accessory]
    ) {

        heading.textContent =
            brand.toUpperCase();


        const models =
            accessories[accessory][brand];


        models.forEach(
            function (model) {

                const card =
                    document.createElement(
                        "div"
                    );


                card.className =
                    "model-card";


                card.innerHTML = `

                    <div class="model-image">

                        <img
                            src="${model.image}"
                            alt="${model.name}"
                        >

                    </div>

                    <h2>
                        ${model.name}
                    </h2>

                    <h3>
                        ₹${model.price}
                    </h3>

                    <button>
                        SELECT MODEL
                    </button>

                `;


                card.onclick =
                    function () {

                        localStorage.setItem(
                            "selectedModel",
                            JSON.stringify(model)
                        );


                        window.location.href =
                            "order.html";

                    };


                modelList.appendChild(
                    card
                );

            }
        );

    }

}



// ========================================
// 4. LOAD ORDER PAGE
// ========================================

if (
    window.location.pathname.endsWith(
        "order.html"
    )
) {

    const model =
        JSON.parse(
            localStorage.getItem(
                "selectedModel"
            )
        );


    if (model) {

        document.getElementById(
            "productImage"
        ).src =
            model.image;


        document.getElementById(
            "productName"
        ).textContent =
            model.name;


        document.getElementById(
            "productPrice"
        ).textContent =
            model.price;


        document.getElementById(
            "priceBox"
        ).textContent =
            model.price;


        document.getElementById(
            "totalBox"
        ).textContent =
            model.price;


        document.getElementById(
            "selectedProduct"
        ).value =
            model.name;

    }



    // Quantity calculation

    const quantity =
        document.getElementById(
            "quantity"
        );


    quantity.addEventListener(
        "change",
        function () {

            const qty =
                Number(this.value);


            const total =
                model.price * qty;


            document.getElementById(
                "quantityBox"
            ).textContent =
                qty;


            document.getElementById(
                "totalBox"
            ).textContent =
                total;

        }
    );



    // PLACE ORDER

    document.getElementById(
        "orderForm"
    ).addEventListener(
        "submit",
        function (event) {

            event.preventDefault();


            const name =
                document.getElementById(
                    "fullName"
                ).value;


            alert(
                "Order placed successfully!\n\n" +
                "Customer: " +
                name +
                "\nProduct: " +
                model.name +
                "\nTotal: ₹" +
                document.getElementById(
                    "totalBox"
                ).textContent
            );

        }
    );

}



